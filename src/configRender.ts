/**
 * LiteLLM config.yml rendering — pure string logic, no vscode/http, so it is
 * unit-testable in plain Node (see test/). proxy.ts re-exports it for the
 * existing import sites.
 */

export interface ExportOptions {
  modelMap: Record<string, string>;
  defaultDeployment: string;
  apiBase: string;
  apiKey: string;
  /** when set, every exported deployment gets a LiteLLM-native fallback to this model */
  fallbackModel?: string;
}

/**
 * Generate a LiteLLM config.yml whose model_list uses the Copilot model names
 * as `model_name` (that is what the picker sends) mapped to the user's
 * deployments.
 */
export function renderLiteLLMConfig(opts: ExportOptions): string {
  const lines: string[] = [
    '# Generated by vscode-litellm on ' + new Date().toISOString(),
    '# model_name = the model name GitHub Copilot sends; litellm_params.model = your deployment.',
    'model_list:',
  ];
  const entries = Object.entries(opts.modelMap ?? {});
  for (const [copilotName, mapped] of entries) {
    const model = mapped || opts.defaultDeployment || copilotName;
    lines.push(`  - model_name: ${quoteYaml(copilotName)}`);
    lines.push('    litellm_params:');
    lines.push(`      model: ${quoteYaml(model)}`);
    if (opts.apiBase) lines.push(`      api_base: ${quoteYaml(opts.apiBase)}`);
    if (opts.apiKey) lines.push(`      api_key: ${quoteYaml(opts.apiKey)}`);
  }
  if (entries.length === 0) {
    lines.push('  # no modelMap entries — add some via "LiteLLM Proxy: Configure Model Map"');
  }
  lines.push('');
  lines.push('# Known Copilot-only paths that plain LiteLLM 404s on (see docs/spike.md):');
  lines.push('#   POST /v1/engines/<model>/completions   (code completions)');
  lines.push('#   GET  /models                           (model picker fallback list)');
  lines.push('#   /_ping, /agents*, /skills, /search, /models/session');
  const fallback = (opts.fallbackModel ?? '').trim();
  lines.push('litellm_settings:');
  lines.push('  drop_params: true');
  if (fallback) {
    // LiteLLM-native fallback: if a deployment errors, LiteLLM retries on
    // `fallback`. (Only fires for models that exist — unknown models 404 first.)
    const fb: string[] = [];
    for (const [copilotName, mapped] of entries) {
      const deployment = mapped || opts.defaultDeployment || copilotName;
      if (deployment === fallback) continue; // no self-fallback
      fb.push(`    - ${quoteYaml(copilotName)}: [${quoteYaml(fallback)}]`);
    }
    if (fb.length > 0) {
      lines.push('  fallbacks:', ...fb);
    } else {
      lines.push('  # fallbackModel equals every deployment — nothing to emit');
    }
  }
  lines.push('');
  return lines.join('\n');
}

export function quoteYaml(s: string): string {
  return /^[A-Za-z0-9_\-./:]+$/.test(s) ? s : JSON.stringify(s);
}
